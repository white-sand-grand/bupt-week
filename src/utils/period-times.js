/**
 * 海南校区节次作息（2026-10 用户提供：上午与北京一致，7 节起整体后移，
 * 且海南共 15 节、北京 14 节）。教务接口里没有这张表，只能内置。
 *
 * 北京时刻不在这里——课表对象 periods[].time 就是北京时刻（移动教务与桌面
 * 教务两个数据源一致，见 services/jwglweixin.js 的 SLOT_TIMES）。
 */
export const HAINAN_SLOT_TIMES = [
  ['08:00', '08:45'], ['08:50', '09:35'], ['09:50', '10:35'], ['10:40', '11:25'],
  ['11:30', '12:15'], ['13:00', '13:45'], ['14:00', '14:45'], ['14:50', '15:35'],
  ['15:50', '16:35'], ['16:40', '17:25'], ['17:30', '18:15'], ['18:20', '19:05'],
  ['19:30', '20:15'], ['20:20', '21:05'], ['21:10', '21:55'],
]

/** 节次号 → 海南时刻串（"14:00~14:45"）。超出作息表（>15 节）返回空串，不显示该行。 */
export function hainanPeriodTime(number) {
  const slot = HAINAN_SLOT_TIMES[number - 1]
  return slot ? `${slot[0]}~${slot[1]}` : ''
}
